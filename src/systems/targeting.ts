/**
 * Выбор ОБЩЕЙ цели для роя.
 *
 * Зачем это существует. Каждый мот сам искал ближайшего врага (`nearestEnemy` в
 * `ally.ts`), и стая из шести мотов размазывала урон по толпе: по три укуса
 * танку, по два стрелку, по одному погонялам. Ощущение игрока из плейтеста —
 * «ветка суммонера проседает по урону» и «танки слишком плотные, три
 * настакалось» — это одно и то же явление с двух сторон: суммарный урон стаи
 * нормальный (замер стендом: 50–63 убийства против 11–31 у механика), но он
 * не ДОБИВАЕТ, и крупная цель стоит дольше, чем игрок терпит.
 *
 * Решение: стая выбирает одну цель на всех. Фокус — это урон, который видит
 * игрок: танк или элита тают на глазах, а не держат полполя, пока моты
 * расклёвывают кого попало. Числа урона не меняются: меняется только то, КУДА
 * он падает, поэтому кривая сложности не сдвигается — сдвигается читаемость боя.
 *
 * Правила выбора (и почему именно такие):
 *  1. Приоритет угрозы важнее близости. Рой решает ту задачу, которую игрок не
 *     может решить ногами: танка нельзя увести, стрелка надо догнать, а
 *     погоняла сама придёт. Танк — главная цель, элита вторая, стрелок третья.
 *  2. Из равных по приоритету берётся ближайший к ИГРОКУ, а не к моту: моты
 *     живут в крыле игрока, и дальняя цель за кадром не должна растягивать стаю
 *     в нитку через всю арену.
 *  3. Дальние цели не берутся вообще: стая работает в радиусе погони от игрока,
 *     а за ним моты возвращаются в строй. Это прежнее правило, только центр
 *     радиуса один на всех.
 *  4. Мёртвые не берутся: труп остаётся в списке до resolveKills, и выбор по
 *     списку без этой проверки уводил бы урон в уже убитого.
 *
 * Модуль чистый: ни Phaser, ни состояния, ни времени. Кандидат приходит
 * структурным типом (pos, hp, kind, elite) — сцена передаёт свой массив врагов
 * как есть, без копий: в игровом шаге аллокаций быть не должно, и ради выбора
 * цели это правило нарушать нельзя. Поэтому поведение роя проверяется тестами
 * без браузера, а не только глазами в плейтесте.
 */
import type { Vec2 } from '../core/math';
import type { EnemyKindId } from '../config/enemyKinds';
import type { EliteModifier } from './spawnDirector';

/**
 * Кандидат в цель роя: ровно те поля, которые нужны выбору. Структурный тип, а
 * не класс: Enemy его удовлетворяет как есть, и модуль не тянет за собой Phaser.
 */
export interface FocusCandidate {
  pos: Vec2;
  hp: number;
  kind: { id: EnemyKindId };
  elite: EliteModifier | null;
}

/**
 * Приоритет цели: чем опаснее цель, тем выше число.
 *
 * Веса нарочито разведены, а не «танк 3, стрелок 2, элита 1». Элита — это вид
 * ПЛЮС свойство, поэтому её надбавка (+5) выше танка (+4): элитный погоняла —
 * более приоритетная цель, чем обычный танк (у неё и щит, и скорость, и
 * нестабильность), но элитный танк — по-прежнему номер один (+9). Стрелок —
 * третий (+2): его угроза летит, и её можно увести ногами. Погоняла — база
 * (0): её угроза в кольце, а кольцо игрок разводит сам.
 */
export function focusPriority(kindId: EnemyKindId, elite: EliteModifier | null): number {
  let priority = 0;
  if (kindId === 'tank') priority += 4;
  else if (kindId === 'shooter') priority += 2;
  if (elite !== null) priority += 5;
  return priority;
}

/**
 * Общая цель роя или null (моты возвращаются в строй).
 *
 * Квадрат радиуса приходит аргументом: вызывающий считает его один раз на шаг,
 * а не на каждого кандидата. Решение детерминировано и не зависит от порядка
 * в списке при разных приоритетах; при равных — от близости, что тоже
 * однозначно, если только два врага не стоят в одной точке (тогда порядок в
 * списке и так не влияет: цели неразличимы).
 */
export function pickFocusTarget<T extends FocusCandidate>(
  candidates: readonly T[],
  from: Vec2,
  rangeSq: number,
): T | null {
  // Обобщение, а не FocusCandidate: вызывающему нужен ЕГО тип (сцена передаёт
  // массив врагов и хочет получить врага, а не «что-то с pos и hp»).
  let best: T | null = null;
  let bestPriority = -1;
  let bestDist2 = Infinity;
  for (const candidate of candidates) {
    if (candidate.hp <= 0) continue;
    const dx = candidate.pos.x - from.x;
    const dy = candidate.pos.y - from.y;
    const dist2 = dx * dx + dy * dy;
    if (dist2 > rangeSq) continue;
    const priority = focusPriority(candidate.kind.id, candidate.elite);
    // Строго «выше» по приоритету и строго «ближе» при равенстве: равные цели
    // в одной точке не заставляют выбор дёргаться между собой.
    if (priority > bestPriority || (priority === bestPriority && dist2 < bestDist2)) {
      best = candidate;
      bestPriority = priority;
      bestDist2 = dist2;
    }
  }
  return best;
}
