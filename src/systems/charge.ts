import { TUNING } from '../config/tuning';

/**
 * «Ток» — общая энергия фигур и единственный ресурс забега.
 *
 * Добывается не уроном: ствола у игрока нет, урон наносят только фигуры. Ток
 * приносят батареи с поля, поэтому выводок работает ровно настолько, насколько
 * игрок успевает двигаться. Модуль чистый: ни Phaser, ни времени — только
 * числа, которые ему передают, поэтому правила проверяются тестами без браузера.
 */
export interface Charge {
  amount: number;
  /**
   * Потолок пула. Живёт в состоянии, а не берётся из tuning: его растит ветка
   * энергии, то есть у каждого билда он свой.
   */
  cap: number;
  /**
   * Сколько Тока ЗАНЯТО живыми фигурами. Каждая поставленная фигура держит свой
   * залог, пока стоит на поле, и этот залог недоступен для новых постановок.
   *
   * Зачем. После перехода на плату за постановку доход перекрывал расход в
   * несколько раз (забег 1:23: 173 дохода против 40 расхода), и ветка энергии
   * стала ненужной: Ток копился сам. Залог возвращает её к делу и делает то, что
   * делает резервация маны в PoE 2 и число фигур у Соломона: сила фигур платится
   * ПОСТОЯННОЙ долей бюджета, а не налогом за каждое действие. Больше фигур —
   * меньше свободного Тока на новые, поэтому «Ёмкость» и «Резерв» снова решают.
   */
  held: number;
}

export function createCharge(cap: number): Charge {
  return { amount: 0, cap, held: 0 };
}

/** Свободный Ток: то, чем реально можно распоряжаться. Потолок минус залог. */
export function avail(c: Charge): number {
  return Math.max(0, c.cap - c.held);
}

/**
 * Занять Ток под фигуру. Залог больше свободного остатка не берётся: фигура без
 * покрытия превратила бы бюджет в фикцию — она бы стояла, а Тока на неё не было.
 */
export function hold(c: Charge, amount: number): boolean {
  if (c.held + amount > c.cap) return false;
  c.held += amount;
  if (c.amount > avail(c)) c.amount = avail(c);
  return true;
}

/** Вернуть залог (фигура ушла с поля). */
export function release(c: Charge, amount: number): void {
  c.held = Math.max(0, c.held - amount);
}

/**
 * Полный сброс залога на старте забега. Пул создаётся один раз на сцену, а сцена
 * переживает перезапуск, поэтому залог ОБЯЗАН обнуляться вместе с потолком.
 * Забыл — и следующий забег начинался бы с занятым бюджетом от прошлого:
 * шкала уходила за единицу, батареи не начислялись, а фигуры не ставились.
 */
export function clearHold(c: Charge): void {
  c.held = 0;
}

/** Начисление за подбор. Больше СВОБОДНОГО Тока пул не берёт. */
export function add(c: Charge, amount: number): void {
  c.amount = Math.min(avail(c), c.amount + amount);
}

/**
 * Меняет потолок и подрезает пул по СВОБОДНОМУ остатку: билд не должен держать
 * лишнее, а залог за живыми фигурами важнее роста потолка.
 *
 * Подрезка именно по свободному Току — не педантизм: карта «Ёмкость» растёт
 * посреди забега, когда залог уже занимает половину бюджета, и подрезка по
 * физическому потолку оставляла пул выше свободного (норма пула уходила за
 * единицу, шкала HUD падала с отрицательным числом). Нашёл это стенд.
 */
export function setCap(c: Charge, cap: number): void {
  c.cap = cap;
  if (c.amount > avail(c)) c.amount = avail(c);
}

export function canAfford(c: Charge, cost: number): boolean {
  return c.amount >= cost && cost <= avail(c);
}

/** Списывает цену постановки. false — свободного Тока не хватает, пул не тронут. */
export function spend(c: Charge, cost: number): boolean {
  if (!canAfford(c, cost)) return false;
  c.amount -= cost;
  return true;
}

/**
 * Затухание: пул тает, пока он выше защищённого порога, и ниже порога не идёт.
 *
 * И скорость, и порог приходят аргументами: их меняют карты, а сам модуль про
 * них не знает. Порог задан ДОЛЕЙ потолка, а не числом Тока, по двум причинам:
 * карта «Резерв» обязана работать одинаково на пуле в 20 и на пуле в 60, а
 * «Ёмкость» перестаёт быть мёртвой — она растит защищённую часть пула. Ноль
 * возвращает прежнее поведение: пул уходит в ноль.
 */
export function stepCharge(
  c: Charge,
  dt: number,
  decayPerSec: number,
  reserveFraction = 0,
): void {
  if (decayPerSec <= 0) return;
  const floor = c.cap * reserveFraction;
  if (c.amount <= floor) return;
  c.amount = Math.max(floor, c.amount - decayPerSec * dt);
}

/**
 * 0..1 — для шкалы HUD и будущего агро врагов. От СВОБОДНОГО Тока, с потолком
 * единицы: шкала обязана остаться шкалой даже при рассогласовании чисел.
 */
export function chargeNorm(c: Charge): number {
  const free = avail(c);
  return free > 0 ? Math.min(1, c.amount / free) : 0;
}

/** Полный пул билда — стартовое значение для сцены. */
export function baseCap(): number {
  return TUNING.charge.capBase;
}
