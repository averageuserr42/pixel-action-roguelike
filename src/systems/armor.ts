/**
 * Броня игрока: слой, который гасит ДАЛЬНИЙ урон.
 *
 * Это единственный невыполненный кусок плана «виды врагов» (Task 5 — «броня и
 * два канала урона»). Замер того плана уже показал болезнь: стрелок в изоляции
 * снимал все три удара пула, и ответа на обстрел, кроме рывка, у игрока не было.
 * Контакт тем временем давно честен: он телеграфирован замахом, и наказание за
 * него — часть чтения боя. Снаряд же ЛЕТИТ, и требовать от игрока рывка на
 * каждую пулю — это требовать кулдаун вместо игры.
 *
 * Как план адаптирован под текущий контракт (пул на три удара, коммит 1513f96).
 * В плане было «контакт убивает всегда» — при пуле ударов это превратилось бы в
 * «контакт всегда берёт удар из пула», что здесь и записано. Правила:
 *
 *  1. Канал `contact` (тело врага) идёт мимо брони ВСЕГДА: броня — про
 *     дистанционный урон, а не про прощение ошибки в упор.
 *  2. Канал `ranged` (снаряд стрелка, взрыв нестабильной элиты) тратит ровно
 *     один слой. Залп в одном кадре теряет один слой, а не все: окно
 *     неуязвимости после срабатывания брони задаёт сцена
 *     (`TUNING.player.armorHitInvulnMs`), модуль про него не знает.
 *  3. Слой восстанавливается после `regenMs` БЕЗ попаданий: броня — окно
 *     передышки между залпами, а не постоянный купол. Попадание сбрасывает
 *     таймер — иначе игрок жил бы по расписанию регена, а не по своему.
 *  4. Слои не уходят в минус и не «копятся»: пустая броня — это ноль, полная —
 *     `layers`, и всё.
 *
 * Модуль чистый: ни Phaser, ни таймеров внутри — время приходит шагом, поэтому
 * правила проверяются тестами без браузера (это требование плана: тестируемый
 * модуль не импортирует Phaser).
 */

/** Канал урона: чем именно игрок поплатился. */
export type DamageChannel = 'contact' | 'ranged';

export interface ArmorState {
  /** Сколько слоёв сейчас заряжено (0..layers). */
  charged: number;
  /** Полный запас слоёв. Меньше единицы — брони нет вовсе. */
  layers: number;
  /** Через сколько миллисекунд без попаданий возвращается слой. */
  regenMs: number;
  /** Сколько миллисекунд прошло с последнего попадания. */
  sinceHitMs: number;
}

export function createArmor(layers: number, regenMs: number): ArmorState {
  return {
    charged: Math.max(0, Math.floor(layers)),
    layers: Math.max(0, Math.floor(layers)),
    regenMs,
    sinceHitMs: 0,
  };
}

/** Шаг времени: восстановление идёт только после паузы без попаданий. */
export function stepArmor(armor: ArmorState, dt: number): void {
  armor.sinceHitMs += dt * 1000;
  if (armor.charged >= armor.layers) return;
  if (armor.sinceHitMs < armor.regenMs) return;
  // Один слой за раз и таймер заново: серия слоёв приходит дозированно, а не
  // полным куполом одним кадром после выдержки.
  armor.charged++;
  armor.sinceHitMs = 0;
}

/**
 * Пропустить удар через броню. true — удар ПОГЛОЩЁН (жизнь цела),
 * false — он идёт в пул ошибок игрока.
 *
 * Контакт никогда не поглощается: см. правило 1. Снаряд тратит слой и
 * сбрасывает таймер восстановления (правило 3).
 */
export function absorb(armor: ArmorState, channel: DamageChannel): boolean {
  if (channel === 'contact') return false;
  if (armor.charged <= 0) return false;
  armor.charged--;
  armor.sinceHitMs = 0;
  return true;
}
