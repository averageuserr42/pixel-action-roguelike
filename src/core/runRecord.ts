import type { BranchId } from './progression';

export type ControlScheme = 'keyboard' | 'touch';
/**
 * Режим давления врагов. Часть опознания прогона, а не украшение: результат
 * «хардкора» и «обычного» — это результаты разных игр, и в одной таблице им
 * места нет.
 */
export type RunMode = 'normal' | 'hardcore';

/**
 * Запись прогона. Профиль управления фиксируется с самого начала, потому что
 * рекорды для клавиатуры и для тача обязаны жить в разных таблицах: забег на
 * двух пальцах и забег мышью — разные условия, и поделить их задним числом
 * будет невозможно.
 *
 * Клиент не может проверить это сам в принципе. Смысл записи в том, чтобы
 * микросервер (когда он появится) получил профиль вместе с результатом и сам
 * решил, в какую таблицу его класть.
 *
 * Билд (picks) — не украшение, а часть того же вопроса: «что за забег был».
 * Две таблицы для способа управления бессмысленны, если один забег шёл с
 * турелью и батареями, а другой — на двух мотах. Профессия (specialty)
 * отвечает на тот же вопрос с другой стороны — кем игрок этот забег прошёл.
 *
 * Версия 5: ствола у игрока больше нет, поэтому «режим огня» из записи исчез.
 * Записи версии 4 описывают игру, которой уже не существует, и складывать их с
 * новыми в одну таблицу нельзя.
 *
 * Версия 6: у игрока появилась броня дальнего боя (systems/armor). Время
 * выживания при щите и без него — результаты разных игр, и сравнивать их в
 * одной таблице нельзя: забег, сыгранный без брони, выглядит короче не из-за
 * игрока, а из-за правил. История такие записи отсекает (runHistory), а
 * хранилище меняет ключ — см. HISTORY_KEY.
 */

/**
 * Правила, которыми играется забег. Одно число на все контракты: смена любого
 * из них (урон, экономика, защита) поднимает версию, и записи разных версий
 * расходятся по таблицам. Тип поля ссылается на константу, чтобы число было
 * в одном месте: расходится объявление и литерал — и таблица снова смешается.
 */
export const RUN_RECORD_VERSION = 6;

export interface RunRecord {
  version: typeof RUN_RECORD_VERSION;
  seed: number;
  /** Режим, в котором игрался прогон. Меняется только на экране смерти. */
  mode: RunMode;
  control: ControlScheme;
  /** Менялся ли способ управления по ходу прогона: такой прогон недействителен. */
  changedDuringRun: boolean;
  /** Взятые карты по порядку: это и есть билд забега. */
  picks: string[];
  /**
   * Профессия забега: ветка, которую игрок довёл до порога, или null, если не
   * довёл ни одну. Пишется в момент закрепления, а не выводится из picks: иначе
   * смена правил карт пересчитала бы задним числом уже сыгранные прогоны.
   */
  specialty: BranchId | null;
  /** Уровень, до которого забег дожил. */
  level: number;
}

export interface RunProfile {
  seed: number;
  mode: RunMode;
  control: ControlScheme;
  changedDuringRun: boolean;
}

/**
 * Запись собирается из двух частей: профиль (кто играет и как) и билд (что
 * взято). Профиль меняется редко и с оговорками, билд — каждый уровень,
 * поэтому складывать их в одну структуру и переписывать целиком дешевле, чем
 * синхронизировать два независимых места.
 */
export function createRunRecord(
  profile: RunProfile,
  picks: readonly string[],
  level: number,
  specialty: BranchId | null,
): RunRecord {
  return {
    version: RUN_RECORD_VERSION,
    seed: profile.seed,
    mode: profile.mode,
    control: profile.control,
    changedDuringRun: profile.changedDuringRun,
    // Копия, а не ссылка: запись уезжает дальше (тесты, будущий сервер) и не
    // должна меняться, если билд продолжит расти.
    picks: [...picks],
    specialty,
    level,
  };
}
