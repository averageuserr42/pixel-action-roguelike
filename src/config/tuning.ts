/**
 * Числа давления врагов. Разложены по режимам целиком, а не набором правок
 * поверх «обычного»: режим — это осознанный выбор игрока, и он должен читаться
 * одним куском, а не собираться из чужих значений.
 */
/**
 * Числа снабжения Током: как доход растёт вместе с уровнем игрока. Строка
 * целиком на режим — по той же причине, что и давление врагов: режим читается
 * одним куском, а не собирается из чужих значений.
 */
export interface ChargeSupply {
  /** Сколько Тока даёт батарея на первом уровне. */
  batteryValue: number;
  /** Через столько уровней батарея дорожает на единицу. */
  valueEveryLevels: number;
  /** Пауза между батареями на первом уровне. */
  spawnIntervalMs: number;
  /** На сколько миллисекунд пауза короче за каждый уровень. */
  spawnIntervalPerLevelMs: number;
  /** Ниже этой паузы темп не растёт: каша из предметов — не доход, а мусор. */
  spawnIntervalMinMs: number;
  /** Сколько батарей лежит на поле на первом уровне. Это запас, а не темп. */
  onField: number;
  /** Через столько уровней на поле помещается ещё одна батарея. */
  onFieldEveryLevels: number;
  /** Сколько Тока даёт осколок с убитого на первом уровне. */
  dropValue: number;
  /** Через столько уровней осколок дорожает: он платит за жирного врага. */
  dropEveryLevels: number;
  /**
   * Сколько осколок лежит. Короткое окно — это и есть риск: за наградой надо
   * сходить туда, где сейчас стоят враги.
   */
  dropTtlMs: number;
}

