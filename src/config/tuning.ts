/**
 * Числа давления врагов. Разложены по режимам целиком, а не набором правок
 * поверх «обычного»: режим — это осознанный выбор игрока, и он должен читаться
 * одним куском, а не собираться из чужих значений.
 */
export interface EnemyPressure {
  /** Сколько врагов держим живыми на первом уровне. */
  baseEnemies: number;
  /** Каждые столько уровней игрока к этому числу прибавляется ещё один враг. */
  extraEnemyEveryLevels: number;
  /** Потолок живых врагов: дальше рост превращался бы в кашу, а не в вызов. */
  maxEnemies: number;
  /** Скорость подхода к игроку. Ниже рывка — иначе замах не читается. */
  seekSpeed: number;
  /** Дальность замаха: она же радиус кольца, по которому ходят враги. */
  windupRangeFactor: number;
  /** Пауза между рывками одного врага. */
  chargeCooldownMs: number;
  windupMs: number;
  chargeSpeed: number;
  chargeSpeedPerLevel: number;
  chargeSpeedCap: number;
  /** Пауза до следующего врага, пока на поле меньше целевого числа. */
  spawnIntervalMs: number;
}

