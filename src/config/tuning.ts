export type SfxKind = 'pickup' | 'hit' | 'kill' | 'dash' | 'death' | 'level';

/**
 * Голос одного звука. Файлов в проекте нет — звук синтезируется осциллятором,
 * поэтому эти числа И ЕСТЬ звук: частота, куда тон уезжает за длительность,
 * форма волны и громкость. Подъём тона читается как «взял», спад — как «удар».
 */
export interface SfxVoice {
  wave: OscillatorType;
  freq: number;
  toFreq: number;
  durMs: number;
  gain: number;
}

/**
 * Ступень кривой забега: с этой секунды число врагов, темп их прихода и шанс
 * элиты берутся отсюда ЦЕЛИКОМ.
 *
 * Почему по времени, а не только по уровню. Уровень растёт от убийств, а
 * убийства — от фигур: замкнутый круг, в котором слабый забег получает слабое
 * давление, а сильный — сильное, и разброс только растёт. Замер девяти раундов
 * это подтвердил: хардкор стабильно кончался на 6-18 секундах, то есть в первой
 * минуте успевало случиться ВСЁ давление сразу. Кривая по времени делает первую
 * минуту разгоном в любом билде, а пик — общим для всех.
 */
export interface PressureStage {
  /** С какой миллисекунды забега действует ступень. */
  atMs: number;
  /** Сколько врагов держим живыми (до прибавки за уровень). */
  enemies: number;
  /** Пауза до следующего врага, пока на поле меньше целевого числа. */
  spawnIntervalMs: number;
  /** Шанс, что очередной враг придёт элитой. Ноль — элит ещё нет. */
  eliteChance: number;
}

export interface EnemyPressure {
  /** Кривая по времени забега: строка целиком, как и остальные числа режима. */
  stages: readonly PressureStage[];
  /** Каждые столько уровней игрока к числу ступени прибавляется ещё один враг. */
  extraEnemyEveryLevels: number;
  /** Потолок живых врагов: дальше рост превращался бы в кашу, а не в вызов. */
  maxEnemies: number;
  /** Скорость подхода к игроку. Ниже рывка — иначе замах не читается. */
  seekSpeed: number;
  /** Дальность замаха: она же радиус кольца, по которому ходят враги. */
  windupRangeFactor: number;
  /** Пауза между рывками одного врага. */
  chargeCooldownMs: number;
  windupMs: number;
  chargeSpeed: number;
  chargeSpeedPerLevel: number;
  chargeSpeedCap: number;
}

